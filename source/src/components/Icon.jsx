function renderNode(n, i) {
  const { elem: Tag, attrs = {}, content = [] } = n;
  return <Tag key={i} {...attrs}>{content.map(renderNode)}</Tag>;
}

export default function Icon({ name, size = 20, className = '', filled = false }) {
  const key = filled && name === 'star' ? 'starFilled' : name;
  const desc = (size < 18 ? ICONS16 : ICONS20)[key];
  if (!desc) return null;
  return (
    <svg
      className={`icon ${className}`}
      width={size}
      height={size}
      viewBox={desc.attrs.viewBox}
      fill="currentColor"
      aria-hidden="true"
      focusable="false"
    >
      {desc.content.map(renderNode)}
    </svg>
  );
}

